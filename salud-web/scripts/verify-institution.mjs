import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.INSTITUTION_TEST_URL || 'http://127.0.0.1:4388';
assert.ok(['127.0.0.1','localhost'].includes(new URL(origin).hostname));
const out = fileURLToPath(new URL('../../.impeccable/review/roles-regression/', import.meta.url));
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge', headless: true });
const errors = [], checks = [];
const check = (message) => checks.push(message);
const shot = async (page, name) => { const toastClose = page.locator('.toast button'); if (await toastClose.isVisible()) await toastClose.click(); await page.evaluate(() => { window.scrollTo(0, 0); return document.fonts.ready; }); await page.screenshot({ path: `${out}/${name}.png`, fullPage: true }); };
try {
  for (const width of [1440, 1280, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, reducedMotion: 'reduce' });
    const p = await context.newPage();
    p.on('pageerror', error => errors.push(`${width}: ${error.message}`));
    await p.goto(`${origin}/acceso`);
    await p.getByRole('button', { name: 'Explorar administración', exact: true }).click();
    await p.getByRole('heading', { name: 'Profesionales', exact: true }).waitFor();
    await p.locator('button.professional-name').filter({hasText:'Dra. Elena Martínez'}).waitFor();
    assert.equal(await p.locator('.institution-profile').count(), 3);
    assert.equal(await p.locator('nav a[href="/agenda"]').count(), 0);
    assert.equal(await p.locator('nav a[href="/mensajes"]').count(), 0);
    const ascendingNames = await p.locator('.professional-name strong').allTextContents();
    await p.getByRole('combobox', { name: 'Ordenar profesionales', exact: true }).selectOption('desc');
    await p.waitForFunction(name => document.querySelector('.professional-name strong')?.textContent?.trim() === name, ascendingNames.at(-1));
    assert.deepEqual(await p.locator('.professional-name strong').allTextContents(), [...ascendingNames].reverse());
    await p.getByRole('combobox', { name: 'Ordenar profesionales', exact: true }).selectOption('asc');
    await p.waitForFunction(name => document.querySelector('.professional-name strong')?.textContent?.trim() === name, ascendingNames[0]);
    await shot(p, width === 1440 ? 'desktop' : width === 390 ? 'mobile' : 'user-1280');
    assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Horizontal overflow ${width}`);
    await p.getByLabel('Sede', { exact: true }).selectOption('ib2');
    assert.equal(await p.locator('.institution-profile').count(), 1);
    await p.getByLabel('Sede', { exact: true }).selectOption('');
    await p.getByRole('searchbox', { name: 'Buscar profesional', exact: true }).fill('inexistente');
    await p.getByRole('heading', { name: 'No hay profesionales para estos filtros' }).waitFor();
    await shot(p, `empty-${width}`);
    await p.getByRole('button', { name: 'Limpiar filtros' }).click();
    await p.getByLabel('Vínculo', { exact: true }).selectOption('ACTIVO');
    await p.locator('button.professional-name').filter({hasText:'Dra. Elena Martínez'}).click();
    await p.getByRole('heading', { name: 'Dra. Elena Martínez', exact: true }).waitFor();
    await shot(p, `detail-${width}`);
    await p.getByRole('button', { name: 'Revisar baja institucional', exact: true }).click();
    await p.getByRole('dialog').waitFor();
    assert.equal(await p.getByRole('button', { name: 'Confirmar baja institucional' }).isDisabled(), true);
    await p.getByRole('checkbox', { name: /Entiendo que esta baja/ }).check();
    await p.getByRole('button', { name: 'Confirmar baja institucional' }).click();
    await p.getByRole('alert').filter({ hasText: 'Este profesional tiene turnos futuros' }).waitFor();
    await shot(p, `departure-conflict-${width}`);
    await p.keyboard.press('Escape');
    assert.equal(await p.getByRole('dialog').isVisible(), false);
    await p.getByRole('button', { name: 'Cerrar detalle profesional' }).click();
    await p.locator('button.professional-name').filter({hasText:'Dr. Diego Suárez'}).click();
    await p.getByRole('button', { name: 'Revisar baja institucional', exact: true }).click();
    await p.getByRole('checkbox', { name: /Entiendo que esta baja/ }).check();
    await p.getByRole('button', { name: 'Confirmar baja institucional' }).click();
    await p.getByRole('heading', { name: 'Dr. Diego Suárez', exact: true }).waitFor();
    await p.locator('#professional-detail').getByText('Vínculo finalizado', { exact: true }).waitFor();
    await p.reload();
    await p.locator('button.professional-name').filter({hasText:'Dra. Elena Martínez'}).waitFor();
    assert.equal(await p.locator('.institution-profile').count(), 2);
    check(`${width}px: directorio, orden A–Z/Z–A, filtros, vacío, detalle, baja bloqueada y baja persistida`);

    await p.getByRole('button', { name: 'Añadir profesional', exact: true }).click();
    await p.locator('#institution-form button[type="submit"], #institution-form .institution-form-actions .primary').click();
    await p.locator('#institution-form [aria-invalid="true"]').first().waitFor();
    await shot(p, `professional-form-${width}`);
    await p.getByLabel('Correo de acceso').fill('ada@example.test');
    await p.getByLabel('Nombre de referencia').fill('Dra. Ada Fernández');
    await p.getByLabel('Matrícula verificada').fill('M.N. 50123');
    await p.locator('#institution-form .institution-form-actions .primary').click();
    await p.locator('button.professional-name').filter({hasText:'Dra. Ada Fernández'}).waitFor();
    await p.getByRole('button',{name:'Ocultar credenciales'}).click();
    const downloadEvent = p.waitForEvent('download');
    await p.getByRole('button', { name: 'Exportar CSV' }).click();
    const download = await downloadEvent;
    assert.match(download.suggestedFilename(), /^profesionales-demo-/);
    check(`${width}px: validación, incorporación y exportación`);

    await p.goto(`${origin}/institucion/equipo`);
    await p.getByRole('heading', { name: 'Equipo y permisos', exact: true }).waitFor();
    await p.getByRole('button', { name: 'Editar facultades de Ana García', exact: true }).click();
    await p.getByRole('checkbox', { name: /Catálogo de prácticas/ }).check();
    await shot(p, `permissions-${width}`);
    await p.getByRole('button', { name: 'Guardar facultades', exact: true }).click();
    await p.locator('#institution-form').waitFor({ state: 'detached' });
    assert.match(await p.locator('.team-profile').filter({ hasText: 'Ana García' }).innerText(), /Catálogo de prácticas/);
    check(`${width}px: actualización de facultades`);

    await p.goto(`${origin}/institucion/sedes`);
    await p.getByRole('heading', { name: 'Sedes y agendas', exact: true }).waitFor();
    await p.getByRole('button', { name: 'Nueva sede', exact: true }).click();
    await p.getByLabel('Nombre', { exact: true }).fill('Sede Oeste');
    await p.getByLabel('Dirección', { exact: true }).fill('Domicilio sintético 123');
    await p.getByRole('button', { name: 'Crear sede', exact: true }).click();
    await p.getByRole('heading', { name: 'Sede Oeste', exact: true }).waitFor();
    await p.getByRole('button', { name: 'Nueva agenda', exact: true }).click();
    await p.getByLabel('Nombre', { exact: true }).fill('Consultorio Oeste');
    await p.getByLabel('Profesional', { exact: true }).selectOption('pr1');
    await p.getByLabel('Sede', { exact: true }).selectOption({ label: 'Sede Oeste' });
    await p.getByRole('button', { name: 'Crear agenda', exact: true }).click();
    await p.getByText('Consultorio Oeste', { exact: true }).waitFor();
    await shot(p, `structure-${width}`);
    check(`${width}px: creación de sede y agenda sin exponer turnos`);

    await p.goto(`${origin}/institucion/politicas`);
    await p.getByRole('heading', { name: 'Políticas de reserva', exact: true }).waitFor();
    await p.getByLabel('Duración de pre-reserva (minutos)').fill('7');
    await p.getByLabel('Referencia de aprobación').fill('Acta de prueba sintética');
    await p.getByRole('button', { name: 'Guardar nueva versión', exact: true }).click();
    await p.getByText('Versión 2', { exact: true }).waitFor();
    await shot(p, `policy-${width}`);
    await p.goto(`${origin}/institucion/auditoria`);
    await p.getByRole('heading', { name: 'Auditoría', exact: true }).waitFor();
    await p.getByText('Política actualizada', { exact: true }).waitFor();
    await shot(p, `audit-${width}`);
    check(`${width}px: política versionada y auditoría de acciones`);

    await p.goto(`${origin}/configuracion`);
    await p.getByRole('button', { name: 'Mi cuenta', exact: true }).waitFor();
    assert.equal(await p.getByRole('button', { name: 'Disponibilidad', exact: true }).count(), 0);
    if (width === 390) {
      await p.getByRole('button', { name: 'Abrir navegación' }).click();
      await p.getByRole('dialog', { name: 'Navegación principal' }).waitFor();
      await shot(p, 'mobile-navigation');
      await p.keyboard.press('Escape');
      assert.equal(await p.getByRole('button', { name: 'Abrir navegación' }).evaluate(el => el === document.activeElement), true);
    }
    await p.getByRole('combobox', { name: 'Explorar como', exact: true }).selectOption('secretaria');
    await p.getByRole('heading', { name: /Tu jornada, en un vistazo/ }).waitFor();
    await p.getByRole('combobox', { name: 'Explorar como', exact: true }).selectOption('profesional');
    await p.getByRole('heading', { name: /Buen día/ }).waitFor();
    assert.equal(await p.locator('nav a[href="/institucion/profesionales"]').count(), 0);
    check(`${width}px: cuenta, navegación por teclado y regresión de otros roles`);
    await context.close();
  }
  assert.deepEqual(errors, []);
  await writeFile(`${out}/functional-results.json`, JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ checks: checks.length, errors }, null, 2));
} finally { await browser.close(); }
